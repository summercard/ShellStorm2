def _face_plus_x(g):
    """把「正面朝 +Y」建好的几何旋转成「正面朝 +X」。

    为什么要这个：本模块所有生成器都必须按「正面 +X」建（v003 招牌反写那一轮定的规矩），
    但配电柜 / 售货机的展开面天然是「宽 × 高」的大面，我按 +Y 写了。
    结果实例 rz=0 时门朝向 +Y（沿街），镜头只看到一块背板 —— 近景实测整柜全黑。

    用 -90° 旋转（(x,y) → (y,-x)）而不是镜像：旋转保持 winding，法线不用重算；
    镜像会翻面，法线全反。
    """
    g.verts = [(v[1], -v[0], v[2]) for v in g.verts]


def c_cabinet_detail(g):
    _cabinet_body(g)
    _face_plus_x(g)


def c_vending_detail(g):
    _vending_body(g)
    _face_plus_x(g)
