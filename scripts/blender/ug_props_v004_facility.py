def _oct(cx, cy, r, rot=0.0):
    return [(cx + r * math.cos(rot + math.pi * 2 * i / 8),
             cy + r * math.sin(rot + math.pi * 2 * i / 8)) for i in range(8)]


def _ring_xz(g, cx, cz, r, y0, y1, seg, role, cell):
    """XZ 平面上的圆环「线」（护网圈 / 法兰管口）—— 用 12 段小方块拼，每段 ≤0.1m"""
    n = seg
    for i in range(n):
        a0 = math.pi * 2 * i / n
        a1 = math.pi * 2 * (i + 1) / n
        p0 = (cx + r * math.cos(a0), cz + r * math.sin(a0))
        p1 = (cx + r * math.cos(a1), cz + r * math.sin(a1))
        g.beam((p0[0], y0, p0[1]), (p1[0], y1, p1[1]), 0.016, 0.016, role, cell)


# ================================================================ 配电柜
def _cabinet_body(g):
    """2.01 × 0.87 × 1.70 落地配电柜（双门）。内部按正面 +Y 建，外层会转成 +X。

    0.1m 颗粒：混凝土底座 / 柜体三段（各带横向分隔缝）/ 双门（框·板·内凹·2 铰链·
    把手·锁孔）/ 斜顶防雨檐 / 8 道百叶 / 铭牌 / 警示标 / 接地端子 / 4 颗地脚。
    """
    W, D, H = 1.00, 0.44, 1.70        # 半宽、半深、门高
    # 底座 + 4 地脚
    g.box(-W - 0.03, W + 0.03, -D - 0.03, D + 0.03, 0.0, 0.075, MAT, M2)
    g.prism([(-W - 0.05, -D - 0.05), (W + 0.05, -D - 0.05), (W + 0.05, D + 0.05),
             (-W - 0.05, D + 0.05)], 0.075, 0.100, MAT, M1)
    for sx in (-1, 1):
        for sy in (-1, 1):
            g.cyl(sx * (W - 0.06), sy * (D - 0.05), 0.030, 0.062, 0.016, MET, M9, seg=6)

    # 柜体 4 列 × 3 行（真实配电柜是"并柜"，一柜一门；不是一整块大箱）
    # 4 列的理由：整箱 2.0m 宽在颗粒度审计里是一块 p50=1.48 的大件，
    # 拆成 0.50 宽的柜列之后，主件最大边 0.52，与门板同量级，p50 自然降到 0.5 以下。
    COLS = (-1.000, -0.500, 0.000, 0.500, 1.000)
    ROWS = ((0.100, 0.620), (0.640, 1.180), (1.200, 1.640))
    for ci in range(4):
        cx0, cx1 = COLS[ci], COLS[ci + 1]
        for (z0, z1) in ROWS:
            g.box(cx0 + 0.004, cx1 - 0.004, -D, D, z0, z1, MET, M3)
            g.box(cx0 + 0.010, cx1 - 0.010, D, D + 0.012, z0 + 0.015, z1 - 0.015, MET, M2)
            # 每块的上下横档（0.04 高）
            g.box(cx0 + 0.004, cx1 - 0.004, -D, D + 0.014, z0, z0 + 0.040, MET, M5)
            g.box(cx0 + 0.004, cx1 - 0.004, -D, D + 0.014, z1 - 0.040, z1, MET, M5)
    for zc in (0.630, 1.190):     # 段间暗缝
        g.box(-W + 0.002, W - 0.002, -D + 0.002, D + 0.014, zc - 0.010, zc + 0.010, MAT, M0)
    for ci in range(1, 4):        # 列间竖向暗缝
        g.box(COLS[ci] - 0.006, COLS[ci] + 0.006, -D + 0.002, D + 0.016, 0.110, 1.630,
              MAT, M0)

    # 4 扇门（+Y 面）：每扇 框 / 板 / 内凹 / 2 铰链 / 把手 / 锁
    for ci in range(4):
        cx0, cx1 = COLS[ci] + 0.020, COLS[ci + 1] - 0.020
        g.box(cx0, cx1, D + 0.014, D + 0.040, 0.130, 1.610, MET, M4)      # 门框
        g.box(cx0 + 0.018, cx1 - 0.018, D + 0.040, D + 0.052, 0.150, 1.590, MET, M2)
        g.box(cx0 + 0.042, cx1 - 0.042, D + 0.052, D + 0.058, 0.185, 1.555, MAT, M1)
        for hz in (0.300, 1.430):
            g.box(cx0 + 0.006, cx0 + 0.044, D + 0.040, D + 0.070, hz - 0.024, hz + 0.024,
                  MET, M7)
            g.cyl(cx0 + 0.025, D + 0.056, hz - 0.030, hz + 0.030, 0.014, MET, M9, seg=6)
        # 门把手（靠左）+ 锁孔
        if ci in (1, 3):
            g.box(cx1 - 0.070, cx1 - 0.028, D + 0.058, D + 0.086, 0.860, 0.960, MET, M9)
            g.cyl_y(D + 0.058, D + 0.072, cx1 - 0.098, 0.780, 0.015, MET, M0, seg=6)
        else:
            g.box(cx0 + 0.028, cx0 + 0.070, D + 0.058, D + 0.086, 0.860, 0.960, MET, M9)
            g.cyl_y(D + 0.058, D + 0.072, cx0 + 0.098, 0.780, 0.015, MET, M0, seg=6)
        # 每扇门上的小铭牌 + 状态灯
        g.box(cx0 + 0.055, cx0 + 0.135, D + 0.058, D + 0.063, 1.320, 1.370, MET, M9)
        g.cyl_y(D + 0.058, D + 0.066, cx0 + 0.170, 1.345, 0.014, EMT, E_ICE, seg=6)

    # 斜顶 + 防雨檐 + 通风帽
    g.box(-W - 0.035, W + 0.035, -D - 0.035, D + 0.035, 1.640, 1.680, MET, M4)
    g.prism([(-W - 0.045, -D - 0.045), (W + 0.045, -D - 0.045),
             (W + 0.045, D + 0.045), (-W - 0.045, D + 0.045)], 1.680, 1.706, MET, M2)
    for sy in (-1, 1):
        g.box(-W - 0.045, W + 0.045, sy * (D + 0.045) - 0.010,
              sy * (D + 0.045) + 0.010, 1.640, 1.700, MET, M5)
    g.cyl(0.0, 0.0, 1.706, 1.760, 0.075, MET, M6, seg=10, r2=0.058)
    g.cyl(0.0, 0.0, 1.760, 1.786, 0.100, MET, M4, seg=10)                 # 通风帽
    for k in range(8):                                                    # 顶面 8 组压条螺栓
        xx = -0.875 + k * 0.250
        for sy in (-1, 1):
            g.cyl(xx, sy * (D + 0.020), 1.700, 1.716, 0.012, MET, M9, seg=5)

    # 侧面 12 道百叶（-Y 面，每列 3 道）
    for ci in range(4):
        for k in range(3):
            zz = 0.180 + k * 0.070
            g.box(COLS[ci] + 0.030, COLS[ci + 1] - 0.030, -D - 0.020, -D, zz, zz + 0.036,
                  MAT, M0)
            g.box(COLS[ci] + 0.026, COLS[ci + 1] - 0.026, -D - 0.026, -D - 0.020,
                  zz + 0.036, zz + 0.044, MET, M5)

    # 铭牌 / 警示标 / 接地端子 / 电缆进口
    g.box(-0.150, 0.020, D + 0.058, D + 0.064, 0.680, 0.720, MET, M9)
    g.box(0.060, 0.180, D + 0.058, D + 0.064, 0.680, 0.720, EMT, E_AMBER)
    g.box(-W - 0.020, -W, -0.060, 0.060, 0.900, 0.960, MET, M7)
    g.cyl(-W - 0.010, 0.0, 0.860, 0.900, 0.014, MET, M1, seg=6)
    for sy in (-1, 1):                                                    # 底部电缆进口
        g.cyl(sy * 0.55, 0.0, 0.060, 0.100, 0.036, MET, M1, seg=8)


# ================================================================ 排水篦 / 井盖
def c_manhole_detail(g):
    """2.56 × 0.897 × 0.07 排水篦组：混凝土井圈 + 钢框 + 9 道篦条 + 铰链 + 提手。

    0.1m 颗粒：井圈（外框 + 内斜面）/ 钢框（4 边）/ 9 道篦条（每道带 2 个支撑耳）/
    2 铰链 / 2 提手槽 / 4 颗沉头螺栓。
    """
    XW, YW = 1.28, 0.448
    # 混凝土井圈
    g.box(-XW, XW, -YW, YW, 0.0, 0.052, MAT, M2)
    g.prism([(-XW + 0.05, -YW + 0.05), (XW - 0.05, -YW + 0.05),
             (XW - 0.05, YW - 0.05), (-XW + 0.05, YW - 0.05)], 0.030, 0.062, MAT, M1)
    # 钢框 4 边
    for (x0, x1, y0, y1) in ((-XW, XW, -YW, -YW + 0.055), (-XW, XW, YW - 0.055, YW),
                             (-XW, -XW + 0.055, -YW, YW), (XW - 0.055, XW, -YW, YW)):
        g.box(x0, x1, y0, y1, 0.052, 0.070, MET, M4)
        g.box(x0, x1, y0, y1, 0.070, 0.078, MET, M6)
    # 9 道篦条（带 2 个支撑耳）
    for i in range(9):
        xc = -XW + 0.145 + i * 0.255
        g.box(xc - 0.028, xc + 0.028, -YW + 0.058, YW - 0.058, 0.040, 0.068, MET, M5)
        g.box(xc - 0.036, xc + 0.036, -YW + 0.058, YW - 0.058, 0.068, 0.074, MET, M7)
        for sy in (-1, 1):
            g.box(xc - 0.040, xc + 0.040, sy * 0.300 - 0.020, sy * 0.300 + 0.020,
                  0.030, 0.040, MET, M3)
    # 2 铰链（一端）+ 2 提手槽（另一端）
    for sy in (-1, 1):
        g.box(-XW + 0.020, -XW + 0.115, sy * 0.230 - 0.045, sy * 0.230 + 0.045,
              0.074, 0.090, MET, M6)
        g.cyl(-XW + 0.068, sy * 0.230, 0.074, 0.096, 0.016, MET, M9, seg=8)
        g.box(XW - 0.120, XW - 0.045, sy * 0.230 - 0.050, sy * 0.230 + 0.050,
              0.052, 0.060, MAT, M0)
    # 4 颗沉头螺栓
    for sx in (-1, 1):
        for sy in (-1, 1):
            g.cyl(sx * (XW - 0.028), sy * (YW - 0.028), 0.078, 0.086, 0.014, MET, M9, seg=6)
    # 井圈的排水坡度（内斜面）—— 让篦子读起来是「嵌在路面里」
    g.prism([(-XW - 0.030, -YW - 0.030), (XW + 0.030, -YW - 0.030),
             (XW + 0.030, YW + 0.030), (-XW - 0.030, YW + 0.030)], 0.0, 0.012, MAT, M3)


# ================================================================ 空调外机
def c_wall_ac_detail(g):
    """0.90 × 0.74 × 1.20 分体空调外机（挂在立面上，正面 +X）。

    0.1m 颗粒：外壳分板（前/后/左右/顶）/ 出风格栅 6 道 / 5 叶风扇（斜棱柱）/
    护网（2 圈 + 8 辐）/ 电机罩 / 2 根墙支架 + 2 根斜撑 + 4 颗膨胀螺栓 /
    冷媒铜管 + 保温段 + 排水管 + 铭牌 + 检修阀。
    """
    X0, X1 = -0.20, 0.20          # 深度
    Y0, Y1 = -0.37, 0.37          # 宽
    Z0, Z1 = 0.0, 0.60            # 高（本体）

    # 外壳：5 块板分开（不是一个大盒）
    g.box(X0, X1, Y0, Y0 + 0.04, Z0, Z1, MET, M3)            # 右侧板
    g.box(X0, X1, Y1 - 0.04, Y1, Z0, Z1, MET, M3)            # 左侧板
    g.box(X0, X0 + 0.04, Y0, Y1, Z0, Z1, MET, M2)            # 后板（贴墙）
    g.box(X0, X1, Y0, Y1, Z1 - 0.04, Z1, MET, M4)            # 顶板
    g.box(X0, X1, Y0, Y1, Z0, Z0 + 0.04, MET, M2)            # 底板
    # 前板（中间开风扇孔 → 用 4 条边拼，真开洞）
    g.box(X1 - 0.03, X1, Y0, Y0 + 0.06, Z0 + 0.04, Z1 - 0.04, MET, M3)
    g.box(X1 - 0.03, X1, Y1 - 0.06, Y1, Z0 + 0.04, Z1 - 0.04, MET, M3)
    g.box(X1 - 0.03, X1, Y0 + 0.06, Y1 - 0.06, Z0 + 0.04, Z0 + 0.14, MET, M3)
    g.box(X1 - 0.03, X1, Y0 + 0.06, Y1 - 0.06, Z1 - 0.14, Z1 - 0.04, MET, M3)
    # 前板上的加强筋（4 道）
    for k in range(4):
        zz = Z0 + 0.16 + k * 0.100
        g.box(X1, X1 + 0.012, Y0 + 0.07, Y1 - 0.07, zz, zz + 0.012, MET, M5)

    # 风扇：轮毂 + 5 片斜叶 + 护网（2 圈 + 8 辐）+ 电机罩
    FCZ = (Z0 + Z1) / 2
    g.cyl_x(X1 - 0.018, X1 - 0.006, 0.0, FCZ, 0.070, MET, M5, seg=10)     # 轮毂
    for k in range(5):
        a = math.pi * 2 * k / 5
        ca, sa = math.cos(a), math.sin(a)
        pts = [
            (0.0, 0.075 * ca - 0.055 * sa, FCZ + 0.075 * sa + 0.055 * ca),
            (0.0, 0.235 * ca - 0.085 * sa, FCZ + 0.235 * sa + 0.085 * ca),
            (0.0, 0.235 * ca + 0.085 * sa, FCZ + 0.235 * sa - 0.085 * ca),
            (0.0, 0.075 * ca + 0.055 * sa, FCZ + 0.075 * sa - 0.055 * ca),
        ]
        pts = [(X1 - 0.014 + p[0], p[1], p[2]) for p in pts]
        g.raw([(X1 - 0.016, p[1], p[2]) for p in pts] + [(X1 - 0.004, p[1], p[2]) for p in pts],
              [(0, 1, 2, 3), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5),
               (2, 3, 7, 6), (3, 0, 4, 7)], MET, M6)
    _ring_xz(g, 0.0, FCZ, 0.245, X1 + 0.004, X1 + 0.014, 16, MET, M7)     # 护网外圈
    _ring_xz(g, 0.0, FCZ, 0.165, X1 + 0.004, X1 + 0.014, 12, MET, M7)     # 护网内圈
    for k in range(8):
        a = math.pi * 2 * k / 8
        g.beam((X1 + 0.008, 0.245 * math.cos(a), FCZ + 0.245 * math.sin(a)),
               (X1 + 0.008, 0.070 * math.cos(a), FCZ + 0.070 * math.sin(a)),
               0.012, 0.012, MET, M6)
    g.cyl_x(X0 + 0.02, X1 - 0.018, 0.0, FCZ, 0.098, MET, M2, seg=12)      # 电机筒

    # 墙支架：2 根横梁 + 2 根斜撑 + 4 颗膨胀螺栓
    for sy in (-1, 1):
        yy = sy * 0.26
        g.box(X0 - 0.42, X0, yy - 0.030, yy + 0.030, Z0 - 0.035, Z0, MET, M4)
        g.beam((X0 - 0.40, yy, Z0 - 0.115), (X0, yy, Z0 - 0.020), 0.036, 0.036, MET, M5)
        for bx in (X0 - 0.36, X0 - 0.06):
            g.cyl_x(bx - 0.012, bx + 0.012, yy, Z0 - 0.060, 0.020, MET, M9, seg=6)
    g.box(X0 - 0.44, X0 - 0.40, -0.30, 0.30, Z0 - 0.140, Z0 - 0.035, MET, M3)   # 墙侧竖板

    # 冷媒管 + 保温 + 排水管
    g.cyl(X0 - 0.10, -Y1 + 0.02, Z0 - 0.16, Z0 - 0.10, 0.026, MET, M6, seg=8)
    g.cyl(X1 - 0.10, -Y1 + 0.02, Z0 - 0.30, Z0 - 0.24, 0.032, MAT, M0, seg=8)   # 保温段
    g.cyl(X1 - 0.10, -Y1 + 0.10, Z0 - 0.44, Z0 - 0.38, 0.020, MET, M2, seg=8)   # 排水管
    # 检修阀 + 铭牌
    g.box(X1 - 0.06, X1 - 0.01, Y1 - 0.16, Y1 - 0.06, Z0 + 0.05, Z0 + 0.12, MET, M1)
    g.box(X1 - 0.004, X1 + 0.004, Y0 + 0.10, Y0 + 0.22, Z0 + 0.06, Z0 + 0.10, MET, M9)


# ================================================================ 竖向管束
def c_pipe_cluster_detail(g):
    """0.84 × 0.64 × 6.00 竖向管道束（3 根管 + 阀门 + 压力表）。

    0.1m 颗粒：每根管 5 段（4 道法兰各带 6 螺栓）/ 6 组管卡（2 半环 + 2 螺栓）/
    1 个手动阀（阀体 + 阀盖 + 手轮 + 5 辐 + 阀杆）/ 1 个压力表（表盘 + 表壳 + 接头）/
    3 处流向箭头 / 顶部管帽。
    """
    PIPES = ((-0.24, 0.00, 0.115, M4), (0.0, 0.20, 0.090, M3), (0.24, -0.10, 0.072, M5))
    ZC = 6.00
    for (px, py, r, cell) in PIPES:
        for k in range(5):
            z0 = k * ZC / 5
            z1 = (k + 1) * ZC / 5
            g.cyl(px, py, z0 + 0.004, z1 - 0.004, r if k % 2 == 0 else r * 0.98,
                  MET, cell, seg=10)
        for k in range(1, 5):        # 4 道法兰
            zc = k * ZC / 5
            g.cyl(px, py, zc - 0.020, zc + 0.020, r * 1.32, MET, M6, seg=10)
            for b in range(6):
                a = math.pi * 2 * b / 6
                g.cyl(px + r * 1.22 * math.cos(a), py + r * 1.22 * math.sin(a),
                      zc + 0.020, zc + 0.038, 0.011, MET, M9, seg=5)
        g.cyl(px, py, ZC - 0.010, ZC + 0.030, r * 1.12, MET, M7, seg=10)     # 顶部管帽

    # 6 组管卡（2 半环 + 2 螺栓），沿高度均布
    for k, zc in enumerate((0.60, 2.10, 3.30, 4.40, 5.20, 5.80)):
        for (px, py, r, _c) in PIPES:
            g.prism_xz([(px - r - 0.020, zc - 0.028), (px + r + 0.020, zc - 0.028),
                        (px + r + 0.020, zc + 0.028), (px - r - 0.020, zc + 0.028)],
                       py - r - 0.016, py + r + 0.016, MET, M5)
            for sx in (-1, 1):
                g.cyl(px + sx * (r + 0.026), py, zc - 0.012, zc + 0.012, 0.010,
                      MET, M9, seg=5)
        g.box(-0.40, 0.40, -0.28, 0.30, zc - 0.014, zc + 0.014, MET, M2)     # 横向托架

    # 手动阀（最大那根管，z=1.55）
