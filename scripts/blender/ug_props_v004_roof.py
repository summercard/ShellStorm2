def _oct(cx, cy, r, rot=0.0):
    return [(cx + r * math.cos(rot + math.pi * 2 * i / 8),
             cy + r * math.sin(rot + math.pi * 2 * i / 8)) for i in range(8)]


def _ring_h(g, cx, cy, r, z0, z1, n, role, cell, t=0.014):
    """水平面内的圆环线（用 n 段小梁拼，单段长度 ≈ 2πr/n）"""
    for i in range(n):
        a0 = math.pi * 2 * i / n
        a1 = math.pi * 2 * (i + 1) / n
        g.beam((cx + r * math.cos(a0), cy + r * math.sin(a0), (z0 + z1) / 2),
               (cx + r * math.cos(a1), cy + r * math.sin(a1), (z0 + z1) / 2),
               t, z1 - z0, role, cell)


