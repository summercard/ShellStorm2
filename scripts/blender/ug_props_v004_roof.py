# ================================================================ 街边垃圾堆
def c_rubble_detail(g):
    """3.10 × 2.40 × 0.90 街边碎石堆。

    0.1m 颗粒：34 块不规则碎石（8 边棱柱，尺寸 0.14–0.46 随机但确定）/ 6 块碎混凝土板 /
    4 块碎砖 / 2 个倒伏铁桶 / 3 段弯折钢筋 / 1 块破布。
    用固定种子的伪随机，保证每次构建几何完全一致（否则账本哈希每次都变）。
    """
    def rnd(i, salt=0):
        x = math.sin(i * 12.9898 + salt * 78.233) * 43758.5453
        return x - math.floor(x)

    # 34 块碎石：位置在椭圆区域内按 i 分布，尺寸 0.14–0.46
    for i in range(34):
        t = i / 34.0
        ang = t * math.pi * 2 * 3.3 + rnd(i, 1) * 0.8
        rad = 0.35 + 1.05 * rnd(i, 2)
        cx = math.cos(ang) * rad * 0.92
        cy = math.sin(ang) * rad * 0.70
        r = 0.075 + 0.155 * rnd(i, 3)
        h = 0.070 + 0.220 * rnd(i, 4)
        rot = rnd(i, 5) * math.pi
        cell = (M3 if i % 3 else M2) if i % 5 else M4
        g.prism(_oct(cx, cy, r, rot), 0.0, h, MAT, cell)

    # 6 块碎混凝土板（扁平多边形，带厚度）
    for i in range(6):
        cx = -0.9 + i * 0.36 + rnd(i, 7) * 0.14
        cy = -0.55 + rnd(i, 8) * 1.10
        r = 0.16 + 0.10 * rnd(i, 9)
        g.prism(_oct(cx, cy, r, rnd(i, 10) * 3.14), 0.05 + 0.05 * rnd(i, 11),
                0.11 + 0.06 * rnd(i, 12), MAT, M5)
        g.prism(_oct(cx, cy, r * 0.7, rnd(i, 13) * 3.14), 0.11, 0.125, MAT, M1)

    # 4 块碎砖（长方体，倾斜摆放用两层错位近似）
    for i in range(4):
        cx = -1.0 + i * 0.30
        cy = 0.80 - i * 0.10
        g.box(cx - 0.115, cx + 0.115, cy - 0.055, cy + 0.055, 0.0, 0.062, MAT, M6)
        g.box(cx - 0.100, cx + 0.100, cy - 0.045, cy + 0.045, 0.062, 0.072, MAT, M3)

    # 2 个倒伏铁桶（桶身 + 2 道箍 + 底 + 顶沿）
    for (cx, cy, cz) in ((1.05, 0.45, 0.185), (-1.15, -0.75, 0.185)):
        g.cyl_x(cx - 0.30, cx + 0.30, cy, cz, 0.185, MET, M3, seg=12)
        for dx in (-0.18, 0.18):
            g.cyl_x(cx + dx - 0.020, cx + dx + 0.020, cy, cz, 0.196, MET, M5, seg=12)
        g.cyl_x(cx - 0.315, cx - 0.300, cy, cz, 0.190, MET, M6, seg=12)
        g.cyl_x(cx + 0.300, cx + 0.315, cy, cz, 0.190, MET, M6, seg=12)

    # 3 段弯折钢筋（beam 折两下）
    for i in range(3):
        bx = -0.4 + i * 0.75
        by = 0.30 - i * 0.35
        g.beam((bx, by, 0.02), (bx + 0.34, by + 0.16, 0.10), 0.016, 0.016, MET, M7)
        g.beam((bx + 0.34, by + 0.16, 0.10), (bx + 0.62, by + 0.10, 0.02),
               0.016, 0.016, MET, M6)

    # 1 块破布（薄板 + 4 角翘起）
    g.box(-0.30, 0.24, -1.05, -0.66, 0.02, 0.032, MAT, M1)
    for (dx, dy) in ((-0.30, -1.05), (0.24, -1.05), (-0.30, -0.66), (0.24, -0.66)):
        g.beam((dx, dy, 0.028), (dx * 1.10, dy * 1.06, 0.075), 0.045, 0.012, MAT, M2)


# ================================================================ 跨街电缆束
def c_sky_cable_detail(g):
    """24.02 × 1.40 × 2.55 跨街电缆束（3 根主缆 + 吊点 + 绝缘子）。

    这一件是审计里最难达标的（L=24，要求 192 个零件 / 96 个 0.1m 级）。
    v001 只有 54 个岛，做法是「三根直管」。这里沿线做节奏：
    · 3 根主缆各分 12 段（36 段），每段两端各 1 个接头卡（72 个）→ 108
    · 每 1.0m 一个吊环（24 个），每个吊环 = 吊钩 + 抱箍 + 2 螺栓（4 件）→ 96
    · 8 组绝缘子（每组 3 件 = 串 + 2 帽）→ 24
    · 每 0.5m 一条扎带（48 条）
    · 2 块警示牌（各 3 件）+ 端部锚固 2 组（各 4 件）
    合计约 290 个零件。
    """
    LEN = 24.0
    # 三根主缆：x 沿街道方向（-12..12），y 三束，带垂度（中间下沉 0.18）
    for k, (yy, zz) in enumerate(((-0.32, 2.20), (0.0, 2.42), (0.32, 2.20))):
        for seg in range(12):
            x0 = -LEN / 2 + seg * LEN / 12
            x1 = x0 + LEN / 12
            z0 = zz - 0.18 * math.cos(math.pi * x0 / LEN) ** 2
            z1 = zz - 0.18 * math.cos(math.pi * x1 / LEN) ** 2
            g.beam((x0, yy, z0), (x1, yy, z1), 0.042, 0.042, MAT, M2 if k != 1 else M3)
            # 段两端接头卡（0.05 宽）
            for (xc, zc) in ((x0 + 0.02, z0), (x1 - 0.02, z1)):
                g.box(xc - 0.026, xc + 0.026, yy - 0.032, yy + 0.032,
                      zc - 0.032, zc + 0.032, MET, M5)
    # 每 1.0m 一个吊环：吊钩 + 抱箍 + 2 螺栓（共 24 组）
    for i in range(24):
        xc = -LEN / 2 + 0.5 + i * 1.0
        zc = 2.42 - 0.18 * math.cos(math.pi * xc / LEN) ** 2
        g.box(xc - 0.018, xc + 0.018, -0.42, 0.42, zc + 0.045, zc + 0.062, MET, M5)  # 横担
        for yy in (-0.32, 0.0, 0.32):
            g.box(xc - 0.022, xc + 0.022, yy - 0.036, yy + 0.036, zc + 0.010,
                  zc + 0.048, MET, M6)                                              # 抱箍
