def crlf(t: str) -> str:
    return t.replace("\r\n", "\n").replace("\n", "\r\n")


def patch(old, new, label):
    data = open(SKILL, "rb").read()
    o = crlf(old).encode("utf-8")
    n = crlf(new).encode("utf-8")
    found = data.count(o)
    if found != 1:
        print("FAIL %-26s 命中 %d 处（期望 1）" % (label, found))
        FAILS.append(label)
        return
    open(SKILL, "wb").write(data.replace(o, n))
    chk = open(SKILL, "rb").read()
    print("OK   %-26s crcrlf=%d lone_lf=%d" % (label, chk.count(b"\r\r\n"), chk.count(b"\n") - chk.count(b"\r\n")))


