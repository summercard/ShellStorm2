def crlf(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\n", "\r\n")


def patch(old: str, new: str, label: str) -> bool:
    data = open(SKILL, "rb").read()
    o = crlf(old).encode("utf-8")
    n = crlf(new).encode("utf-8")
    found = data.count(o)
    if found != 1:
        print("FAIL %-28s 命中 %d 处（期望 1）" % (label, found))
        return False
    open(SKILL, "wb").write(data.replace(o, n))
    chk = open(SKILL, "rb").read()
    print("OK   %-28s crcrlf=%d lone_lf=%d" % (label, chk.count(b"\r\r\n"), chk.count(b"\n") - chk.count(b"\r\n")))
    return True


